#!/usr/bin/env bash
# convert.sh: render the agent .md files into tool-specific formats under integrations/<tool>/.
# Usage: ./scripts/convert.sh [--tool <name>|all] [--out <dir>]
# Never touches user config directories; see install.sh for that.
set -euo pipefail
source "$(dirname "$0")/lib.sh"
ROOT="$(repo_root)"; OUT="$ROOT/integrations"; TOOL=all
while [[ $# -gt 0 ]]; do case "$1" in
  --tool) TOOL="$2"; shift 2;; --out) OUT="$2"; shift 2;;
  -h|--help) sed -n '2,5p' "$0"; exit 0;; *) echo "unknown arg $1" >&2; exit 1;; esac; done

toml_escape() { printf '%s' "$1" | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read(), ensure_ascii=False)[1:-1])'; }
yq() { printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"; }

convert_identity() { local f="$1" tool="$2"; mkdir -p "$OUT/$tool/agents"; cp "$f" "$OUT/$tool/agents/$(basename "$f")"; }
convert_gemini_md() { local f="$1" tool="$2" n d; n="$(get_field name "$f")"; d="$(get_field description "$f")"
  mkdir -p "$OUT/$tool/agents"; { printf -- '---\nname: %s\ndescription: %s\n---\n' "$(yq "$(slugify "$n")")" "$(yq "$d")"; get_body "$f"; } > "$OUT/$tool/agents/$(slugify "$n").md"; }
convert_opencode_md() { local f="$1" n d c; n="$(get_field name "$f")"; d="$(get_field description "$f")"; c="$(get_field color "$f")"
  mkdir -p "$OUT/opencode/agents"; { printf -- '---\nname: %s\ndescription: %s\nmode: subagent\ncolor: %s\n---\n' "$(yq "$n")" "$(yq "$d")" "$(yq "$c")"; get_body "$f"; } > "$OUT/opencode/agents/$(slugify "$n").md"; }
convert_codex_toml() { local f="$1" n d; n="$(get_field name "$f")"; d="$(get_field description "$f")"
  mkdir -p "$OUT/codex/agents"; printf 'name = "%s"\ndescription = "%s"\ndeveloper_instructions = "%s"\n' "$(toml_escape "$n")" "$(toml_escape "$d")" "$(toml_escape "$(get_body "$f")")" > "$OUT/codex/agents/$(slugify "$n").toml"; }
convert_cursor_mdc() { local f="$1" n d; n="$(get_field name "$f")"; d="$(get_field description "$f")"
  mkdir -p "$OUT/cursor/rules"; { printf -- '---\ndescription: %s\nglobs: ""\nalwaysApply: false\n---\n' "$(yq "$d")"; get_body "$f"; } > "$OUT/cursor/rules/$(slugify "$n").mdc"; }
roster_file() { local tool="$1" name="$2" title="$3"; mkdir -p "$OUT/$tool"; local out="$OUT/$tool/$name" f
  { printf '# %s\n\nGenerated by scripts/convert.sh from the Book Agency agents. Activate an agent by name.\n\n' "$title"
    for f in $(agent_files); do printf '\n---\n\n## %s\n\n%s\n\n' "$(get_field name "$f")" "$(get_field description "$f")"; get_body "$f"; done; } > "$out"; }

run_tool() { local t="$1" f
  case "$t" in
    claude-code|copilot) for f in $(agent_files); do convert_identity "$f" "$t"; done;;
    gemini-cli|qwen)     for f in $(agent_files); do convert_gemini_md "$f" "$t"; done;;
    opencode)            for f in $(agent_files); do convert_opencode_md "$f"; done;;
    codex)               for f in $(agent_files); do convert_codex_toml "$f"; done;;
    cursor)              for f in $(agent_files); do convert_cursor_mdc "$f"; done;;
    aider)               roster_file aider CONVENTIONS.md "Book Agency conventions for Aider";;
    windsurf)            roster_file windsurf .windsurfrules "Book Agency rules for Windsurf";;
    *) echo "unknown tool: $t" >&2; return 1;;
  esac; echo "[OK]  $t -> $OUT/$t"; }
if [[ "$TOOL" == all ]]; then for t in "${ALL_TOOLS[@]}"; do run_tool "$t"; done; else run_tool "$TOOL"; fi
